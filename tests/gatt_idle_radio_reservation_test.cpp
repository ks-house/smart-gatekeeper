void reset() {
  delete core;
  std::array<uint8_t, 16> door{};
  door[0] = 1;
  core = new sgk::ProtocolCore(random_source, verifier, door);
  CHECK(core->initialize());
  core->setEnabled(true);
  adapter_state.clear();
  controller.count = 0;
  fast_start_requested_ = in_flight_valid_ = false;
  advertising_ota_busy_ = radio_reserved_ = false;
  drain_calls = 0;
}

void ownedAdmission() {
  reset();
  CHECK(!GattServer::hasIdleRadioReservation());
  CHECK(GattServer::tryReserveIdleRadio());
  CHECK(GattServer::hasIdleRadioReservation());
  CHECK(core->otaBusy() && !GattServer::isOtaBusy());
  CHECK(!GattServer::tryReserveIdleRadio());
  CHECK(drain_calls == 0);
  checkReleasedMutex();
  // Actual ProtocolCore::connect allows busy links; adapter must reject them
  // during a radio reservation, before any accepted ownership is published.
  CHECK(!GattServer::handleConnect(7));
  CHECK(!core->connected());
  GattServer::releaseIdleRadio();
  CHECK(!core->otaBusy() && !GattServer::hasIdleRadioReservation());
  CHECK(GattServer::handleConnect(7));
}

void concurrentAdmissionHasExactlyOneOwner() {
  for (int round = 0; round < 32; ++round) {
    reset();
    std::promise<void> start;
    const auto ready = start.get_future().share();
    auto reservation = std::async(std::launch::async, [ready] {
      ready.wait();
      return GattServer::tryReserveIdleRadio();
    });
    auto connection = std::async(std::launch::async, [ready] {
      ready.wait();
      return GattServer::handleConnect(7);
    });
    start.set_value();
    const bool reserved = reservation.get();
    const bool accepted = connection.get();
    CHECK(reserved != accepted);
    CHECK(core->connected() == accepted);
    CHECK(GattServer::hasIdleRadioReservation() == reserved);
    if (reserved) GattServer::releaseIdleRadio();
  }
  reset();
  // Caller-side serialized checks may re-enter this recursive protocol lock.
  std::unique_lock<std::recursive_mutex> lock(core_mutex);
  CHECK(GattServer::tryReserveIdleRadio());
  auto query = std::async(std::launch::async, [] {
    return GattServer::hasIdleRadioReservation();
  });
  CHECK(query.wait_for(std::chrono::milliseconds(20)) ==
        std::future_status::timeout);
  lock.unlock();
  CHECK(query.get());
  GattServer::releaseIdleRadio();
}

void busyOwnersArePreserved() {
  reset();
  GattServer::setOtaBusy(true);
  CHECK(!GattServer::tryReserveIdleRadio());
  CHECK(GattServer::isOtaBusy() && core->otaBusy());

  reset();
  CHECK(GattServer::handleConnect(7));
  CHECK(!GattServer::tryReserveIdleRadio());
  CHECK(core->connected());

  reset();
  controller.count = 1;  // Controller callback not adopted by the core yet.
  CHECK(!GattServer::tryReserveIdleRadio());

  reset();
  fast_start_requested_ = true;
  CHECK(!GattServer::tryReserveIdleRadio());
  CHECK(fast_start_requested_);

  reset();
  CHECK(adapter_state.acceptConnection({7, 1}));
  const uint8_t packet[] = {1, 2, 3};
  CHECK(adapter_state.enqueueWrite(7, sgk::MessageType::kProof, packet, 3));
  CHECK(!GattServer::tryReserveIdleRadio());
  sgk::PendingWrite pending;
  CHECK(adapter_state.popWrite(&pending));
  CHECK(pending.length == 3 && pending.bytes[2] == 3);

  reset();
  adapter_state.pending_overflow_ = true;
  CHECK(!GattServer::tryReserveIdleRadio());
  CHECK(adapter_state.hasPendingWrite());

  reset();
  adapter_state.output_active_ = true;
  CHECK(!GattServer::tryReserveIdleRadio());
  CHECK(adapter_state.outputActive());

  reset();
  adapter_state.confirmation_pending_ = true;
  CHECK(!GattServer::tryReserveIdleRadio());
  CHECK(adapter_state.confirmationPending());

  reset();
  in_flight_valid_ = true;
  CHECK(!GattServer::tryReserveIdleRadio());
  CHECK(in_flight_valid_);

  reset();
  core->output_count_ = 1;
  CHECK(!GattServer::tryReserveIdleRadio());
  CHECK(core->hasOutput());

  for (auto state : {sgk::SessionState::kHelloReceived,
                     sgk::SessionState::kChallengeIssued,
                     sgk::SessionState::kVerifying,
                     sgk::SessionState::kConsumed,
                     sgk::SessionState::kCompleted}) {
    reset();
    core->state_ = state;
    CHECK(!GattServer::tryReserveIdleRadio());
    CHECK(core->state() == state && !core->otaBusy());
  }
}

void otaOwnershipSurvivesRelease() {
  reset();
  GattServer::setOtaBusy(true);
  GattServer::releaseIdleRadio();
  CHECK(GattServer::isOtaBusy() && core->otaBusy());
  reset();
  CHECK(GattServer::tryReserveIdleRadio());
  GattServer::setOtaBusy(false);
  CHECK(!GattServer::isOtaBusy() && core->otaBusy());
  CHECK(!GattServer::handleConnect(7));
  GattServer::setOtaBusy(true);
  GattServer::releaseIdleRadio();
  CHECK(GattServer::isOtaBusy() && core->otaBusy());
  CHECK(!GattServer::tryReserveIdleRadio());
  GattServer::setOtaBusy(false);
  CHECK(!core->otaBusy());
  CHECK(GattServer::tryReserveIdleRadio());
  GattServer::releaseIdleRadio();
  GattServer::releaseIdleRadio();
  CHECK(!core->otaBusy() && !GattServer::isOtaBusy());
}

void nullOrDisabledCore() {
  reset();
  delete core;
  core = nullptr;
  CHECK(GattServer::tryReserveIdleRadio());
  CHECK(!GattServer::tryReserveIdleRadio());
  GattServer::setOtaBusy(true);
  GattServer::releaseIdleRadio();
  CHECK(GattServer::isOtaBusy());
  GattServer::setOtaBusy(false);
  CHECK(GattServer::tryReserveIdleRadio());
  GattServer::releaseIdleRadio();
  reset();
  core->setEnabled(false);
  CHECK(GattServer::tryReserveIdleRadio());
  CHECK(core->otaBusy());
  CHECK(!GattServer::handleConnect(7));
  GattServer::releaseIdleRadio();
  CHECK(!core->otaBusy());
}
